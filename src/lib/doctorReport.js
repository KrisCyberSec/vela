// 12-week chart-rich PDF doctor report. Premium-tier feature.
// Built with jsPDF; charts are filled-rect bar charts rendered
// inline. Sections: header, profile, 12-week summary stats, top-3
// symptom weekly charts, mood-by-week, sleep-by-week, lifestyle
// patterns, last-4-weeks daily detail, disclaimer footer.

import { jsPDF } from "jspdf";
import { analyzeCorrelations } from "./correlations";


// ─── PDF Report Generator ────────────────────────────────────────────────────

export function generateDoctorReport(logs, profile) {
  // 12-week, chart-rich PDF intended as a 15-second appointment-prep read.
  // Sections: header, profile, 12-week summary stats, top-3 symptom weekly
  // frequency charts, mood and sleep weekly charts, lifestyle + detected
  // patterns, last-4-weeks daily detail, footer.
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 20;
  const contentWidth = pageWidth - margin * 2;
  let y = 20;

  // Brand palette (RGB)
  const CLAY = [196, 133, 108];
  const CLAY_DARK = [140, 78, 50];
  const SAGE = [122, 158, 135];
  const INK = [44, 31, 23];
  const INK_MID = [107, 83, 71];

  function addPage() { doc.addPage(); y = 20; }
  function checkPage(needed) { if (y + needed > 270) addPage(); }

  // Bar chart primitive. Renders a title + 12 bars + baseline + y-axis
  // max/zero labels + x labels. Used three times: symptom frequency,
  // mood by week, sleep by week.
  function drawBarChart({ title, labels, values, max, color, valueFormat, height = 38 }) {
    checkPage(height + 18);
    doc.setFontSize(10);
    doc.setTextColor(...INK);
    doc.text(title, margin, y);
    y += 6;
    const chartWidth = contentWidth;
    const barCount = labels.length;
    const barGap = 2;
    const barW = (chartWidth - barGap * (barCount - 1)) / barCount;
    const baseY = y + height;
    const safeMax = max > 0 ? max : 1;
    doc.setFillColor(...color);
    for (let i = 0; i < barCount; i++) {
      const raw = values[i];
      const v = raw == null || isNaN(raw) ? 0 : Math.max(0, raw);
      const h = (v / safeMax) * height;
      const bx = margin + i * (barW + barGap);
      const by = baseY - h;
      if (h > 0) doc.rect(bx, by, barW, h, "F");
    }
    doc.setDrawColor(180);
    doc.line(margin, baseY, margin + chartWidth, baseY);
    doc.setFontSize(7);
    doc.setTextColor(140);
    const maxLabel = valueFormat ? valueFormat(safeMax) : `${safeMax}`;
    doc.text(maxLabel, margin - 1, y + 2, { align: "right" });
    doc.text("0", margin - 1, baseY, { align: "right" });
    doc.setTextColor(120);
    for (let i = 0; i < barCount; i++) {
      const cx = margin + i * (barW + barGap) + barW / 2;
      doc.text(labels[i], cx, baseY + 4, { align: "center" });
    }
    y = baseY + 10;
  }

  // Header
  doc.setFontSize(22);
  doc.setTextColor(...CLAY_DARK);
  doc.text("Vela Symptom Report", margin, y);
  y += 10;

  doc.setFontSize(10);
  doc.setTextColor(100);
  const now = new Date();
  const twelveWeeksAgo = new Date(now);
  twelveWeeksAgo.setDate(twelveWeeksAgo.getDate() - 84);
  doc.text(
    `Report period: ${twelveWeeksAgo.toLocaleDateString()} – ${now.toLocaleDateString()} (12 weeks)`,
    margin, y
  );
  y += 5;
  doc.text("Generated by Vela · velahealth.health", margin, y);
  y += 10;

  // Line
  doc.setDrawColor(200);
  doc.line(margin, y, pageWidth - margin, y);
  y += 10;

  // Patient profile
  if (profile) {
    doc.setFontSize(14);
    doc.setTextColor(44, 31, 23); // ink
    doc.text("Patient Profile", margin, y);
    y += 8;

    doc.setFontSize(10);
    doc.setTextColor(80);
    const stages = ["Regular cycles", "Perimenopause", "Postmenopause", "Surgical menopause"];
    doc.text(`Hormonal stage: ${stages[profile[0]] || "Not specified"}`, margin, y);
    y += 6;
    const concernLabels = ["Hot flashes & night sweats", "Sleep problems", "Mood changes & anxiety", "Brain fog & fatigue", "Joint pain & body aches", "Weight changes & bloating", "Low libido & dryness", "Heart palpitations"];
    const selectedConcerns = Array.isArray(profile[1]) ? profile[1].map((i) => concernLabels[i]).join(", ") : concernLabels[profile[1]] || "Not specified";
    doc.text(`Primary concerns: ${selectedConcerns}`, margin, y);
    y += 12;
  }

  // Filter to last 12 weeks
  const recentLogs = logs.filter((l) => new Date(l.date) >= twelveWeeksAgo);

  if (recentLogs.length === 0) {
    doc.setFontSize(12);
    doc.setTextColor(100);
    doc.text("No entries logged in the last 12 weeks.", margin, y);
    doc.save("Vela-Symptom-Report.pdf");
    return;
  }

  // Build 12 weekly buckets (oldest → newest) for the charts below.
  const weekBuckets = [];
  for (let w = 11; w >= 0; w--) {
    const start = new Date(now); start.setDate(start.getDate() - (w + 1) * 7); start.setHours(0, 0, 0, 0);
    const end = new Date(now); end.setDate(end.getDate() - w * 7); end.setHours(0, 0, 0, 0);
    weekBuckets.push({ start, end, label: `W${12 - w}` });
  }

  // Summary stats
  doc.setFontSize(14);
  doc.setTextColor(...INK);
  doc.text("12-Week Summary", margin, y);
  y += 8;

  doc.setFontSize(10);
  doc.setTextColor(80);
  doc.text(`Total entries logged: ${recentLogs.length}`, margin, y);
  y += 6;

  // Symptom frequency
  const symptomCount = {};
  recentLogs.forEach((l) => {
    Object.keys(l.symptoms || {}).forEach((s) => {
      symptomCount[s] = (symptomCount[s] || 0) + 1;
    });
  });
  const sortedSymptoms = Object.entries(symptomCount).sort((a, b) => b[1] - a[1]);

  if (sortedSymptoms.length > 0) {
    doc.text("Symptom frequency (top 8, days reported):", margin, y);
    y += 6;
    sortedSymptoms.slice(0, 8).forEach(([name, count]) => {
      checkPage(6);
      doc.text(`  • ${name}: ${count} of ${recentLogs.length} entries`, margin, y);
      y += 5;
    });
    y += 4;
  }

  // Average severity
  const sevTotals = {};
  const sevCounts = {};
  recentLogs.forEach((l) => {
    Object.entries(l.severities || {}).forEach(([s, v]) => {
      if (v > 0) {
        sevTotals[s] = (sevTotals[s] || 0) + v;
        sevCounts[s] = (sevCounts[s] || 0) + 1;
      }
    });
  });
  const sevAvgs = Object.entries(sevTotals).map(([name, total]) => ({
    name, avg: (total / sevCounts[name]).toFixed(1),
  })).sort((a, b) => b.avg - a.avg);

  if (sevAvgs.length > 0) {
    checkPage(10 + Math.min(sevAvgs.length, 6) * 5);
    doc.setFontSize(10);
    doc.text("Average severity (top 6, 1-3 scale):", margin, y);
    y += 6;
    sevAvgs.slice(0, 6).forEach(({ name, avg }) => {
      doc.text(`  • ${name}: ${avg}/3`, margin, y);
      y += 5;
    });
    y += 4;
  }

  // Mood overview
  const moodEntries = recentLogs.filter((l) => l.mood !== null && l.mood !== undefined);
  if (moodEntries.length > 0) {
    checkPage(12);
    const avgMood = (moodEntries.reduce((s, l) => s + l.mood, 0) / moodEntries.length).toFixed(1);
    const moodLabels = ["Very low", "Low", "Neutral", "Good", "Very good"];
    const moodLabel = moodLabels[Math.round(avgMood)] || "Neutral";
    doc.text(`Average mood: ${avgMood}/4 (${moodLabel})`, margin, y);
    y += 10;
  }

  // ── Top-3 symptom weekly-frequency charts
  const top3Symptoms = sortedSymptoms.slice(0, 3).map(([name]) => name);
  if (top3Symptoms.length > 0) {
    checkPage(20);
    doc.setFontSize(14);
    doc.setTextColor(...INK);
    doc.text("Top symptoms by week", margin, y);
    y += 6;
    doc.setFontSize(9);
    doc.setTextColor(...INK_MID);
    doc.text("Days each week the symptom was logged. Higher = more frequent.", margin, y);
    y += 6;
    top3Symptoms.forEach((symptomName) => {
      const counts = weekBuckets.map((b) =>
        recentLogs.filter((l) => {
          const ld = new Date(l.date);
          return ld >= b.start && ld < b.end && l.symptoms?.[symptomName];
        }).length
      );
      drawBarChart({
        title: symptomName,
        labels: weekBuckets.map((b) => b.label),
        values: counts,
        max: 7,
        color: CLAY,
      });
    });
  }

  // ── Mood by week
  const moodByWeek = weekBuckets.map((b) => {
    const samples = recentLogs.filter((l) => {
      const ld = new Date(l.date);
      return ld >= b.start && ld < b.end && l.mood !== null && l.mood !== undefined;
    });
    return samples.length ? samples.reduce((s, l) => s + l.mood, 0) / samples.length : 0;
  });
  if (moodByWeek.some((v) => v > 0)) {
    checkPage(20);
    doc.setFontSize(14);
    doc.setTextColor(...INK);
    doc.text("Mood by week", margin, y);
    y += 6;
    doc.setFontSize(9);
    doc.setTextColor(...INK_MID);
    doc.text("Average mood per week (0 = rough, 4 = great).", margin, y);
    y += 6;
    drawBarChart({
      title: "Mood (0-4)",
      labels: weekBuckets.map((b) => b.label),
      values: moodByWeek,
      max: 4,
      color: SAGE,
      valueFormat: (v) => v.toFixed(0),
    });
  }

  // ── Sleep by week
  const sleepByWeek = weekBuckets.map((b) => {
    const samples = recentLogs.filter((l) => {
      const ld = new Date(l.date);
      return ld >= b.start && ld < b.end && l.context?.sleepHours != null;
    });
    return samples.length ? samples.reduce((s, l) => s + l.context.sleepHours, 0) / samples.length : 0;
  });
  if (sleepByWeek.some((v) => v > 0)) {
    checkPage(20);
    doc.setFontSize(14);
    doc.setTextColor(...INK);
    doc.text("Sleep by week", margin, y);
    y += 6;
    doc.setFontSize(9);
    doc.setTextColor(...INK_MID);
    doc.text("Average sleep hours per week. 7-8h is typical adult range.", margin, y);
    y += 6;
    drawBarChart({
      title: "Sleep (hours)",
      labels: weekBuckets.map((b) => b.label),
      values: sleepByWeek,
      max: 10,
      color: SAGE,
      valueFormat: (v) => `${v}h`,
    });
  }

  // Lifestyle context summary
  const contextLogs = recentLogs.filter((l) => l.context && Object.values(l.context).some((v) => v !== null));
  if (contextLogs.length > 0) {
    checkPage(20);
    doc.setFontSize(14);
    doc.setTextColor(44, 31, 23);
    doc.text("Lifestyle Context Summary", margin, y);
    y += 8;
    doc.setFontSize(10);
    doc.setTextColor(80, 80, 80);
    const sleepDays = contextLogs.filter((l) => l.context.sleepHours !== null);
    if (sleepDays.length > 0) {
      const avgSleep = (sleepDays.reduce((s, l) => s + l.context.sleepHours, 0) / sleepDays.length).toFixed(1);
      doc.text(`Average sleep: ${avgSleep} hours (${sleepDays.length} days reported)`, margin, y); y += 5;
    }
    const stressDays = contextLogs.filter((l) => l.context.stress !== null);
    if (stressDays.length > 0) {
      const avgStress = (stressDays.reduce((s, l) => s + l.context.stress, 0) / stressDays.length).toFixed(1);
      doc.text(`Average stress: ${avgStress}/5 (${stressDays.length} days reported)`, margin, y); y += 5;
    }
    ["caffeine", "alcohol", "exercise"].forEach((trigger) => {
      const tDays = contextLogs.filter((l) => l.context[trigger] === true);
      if (tDays.length > 0) {
        doc.text(`${trigger.charAt(0).toUpperCase() + trigger.slice(1)}: reported on ${tDays.length} of ${contextLogs.length} days`, margin, y); y += 5;
      }
    });
    const corr = analyzeCorrelations(recentLogs);
    if (corr.length > 0) {
      y += 3; doc.text("Detected correlations:", margin, y); y += 5;
      corr.forEach((c) => { checkPage(5); doc.text(`  \u2022 ${c.text}`, margin, y); y += 5; });
    }
    y += 6;
  }

  // Last 4 weeks: daily detail. The earlier 8 weeks are covered by the
  // weekly charts above; printing 84 days of per-entry rows would balloon
  // the PDF and bury the signal.
  const fourWeeksAgo = new Date(now); fourWeeksAgo.setDate(fourWeeksAgo.getDate() - 28);
  const last4WeekLogs = recentLogs.filter((l) => new Date(l.date) >= fourWeeksAgo);
  checkPage(15);
  doc.setFontSize(14);
  doc.setTextColor(...INK);
  doc.text("Last 4 weeks: daily detail", margin, y);
  y += 5;
  doc.setFontSize(9);
  doc.setTextColor(...INK_MID);
  doc.text("Weeks 1-8 are summarized in the charts above.", margin, y);
  y += 8;

  const moodEmojis = ["Very low", "Low", "Neutral", "Good", "Very good"];
  const sortedLogs = [...last4WeekLogs].sort((a, b) => new Date(b.date) - new Date(a.date));

  sortedLogs.forEach((log) => {
    const dateStr = new Date(log.date).toLocaleDateString("en-US", {
      weekday: "short", month: "short", day: "numeric",
    });
    const time = new Date(log.date).toLocaleTimeString("en-US", { hour: "numeric", minute: "2-digit" });
    const symptoms = Object.keys(log.symptoms || {});
    const neededHeight = 12 + (symptoms.length > 0 ? 6 : 0) + (log.notes ? 6 : 0);
    checkPage(neededHeight);

    doc.setFontSize(10);
    doc.setTextColor(44, 31, 23);
    doc.text(`${dateStr} at ${time}`, margin, y);
    if (log.mood !== null && log.mood !== undefined) {
      doc.setTextColor(100);
      doc.text(`Mood: ${moodEmojis[log.mood]}`, margin + 80, y);
    }
    y += 5;

    if (symptoms.length > 0) {
      doc.setTextColor(100);
      const symText = symptoms.map((s) => {
        const sev = log.severities?.[s];
        return sev ? `${s} (${sev}/3)` : s;
      }).join(", ");
      const lines = doc.splitTextToSize(`Symptoms: ${symText}`, contentWidth);
      lines.forEach((line) => {
        checkPage(5);
        doc.text(line, margin, y);
        y += 5;
      });
    }

    if (log.context) {
      const parts = [];
      if (log.context.sleepHours !== null && log.context.sleepHours !== undefined) parts.push(`Sleep: ${log.context.sleepHours}h`);
      if (log.context.stress !== null && log.context.stress !== undefined) parts.push(`Stress: ${log.context.stress}/5`);
      if (log.context.caffeine) parts.push("Caffeine");
      if (log.context.alcohol) parts.push("Alcohol");
      if (log.context.exercise) parts.push("Exercise");
      if (parts.length > 0) {
        doc.setTextColor(110, 110, 110);
        checkPage(5);
        doc.text(`Context: ${parts.join(", ")}`, margin, y);
        y += 5;
      }
    }
    if (log.notes) {
      doc.setTextColor(120);
      const noteLines = doc.splitTextToSize(`Note: "${log.notes}"`, contentWidth);
      noteLines.forEach((line) => {
        checkPage(5);
        doc.text(line, margin, y);
        y += 5;
      });
    }
    y += 3;
  });

  // Footer disclaimer
  checkPage(20);
  y += 5;
  doc.setDrawColor(200);
  doc.line(margin, y, pageWidth - margin, y);
  y += 8;
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text("This report is generated from self-reported data and is intended to support", margin, y);
  y += 4;
  doc.text("conversations with your healthcare provider. It does not constitute medical advice.", margin, y);
  y += 4;
  doc.text("Symptom log is stored on the user's device. Charts and patterns above were computed locally.", margin, y);

  doc.save("Vela-Symptom-Report.pdf");
}
